namespace FluxIndex.Core.Evaluation;

/// <summary>
/// A single QA test case for RAG evaluation.
/// </summary>
/// <param name="Question">The question to ask the RAG system.</param>
/// <param name="ExpectedAnswer">Optional reference answer for similarity scoring.</param>
public record QATestCase(string Question, string? ExpectedAnswer = null);

/// <summary>
/// Evaluation result for a single QA test case.
/// </summary>
public record EvalCaseResult
{
    /// <summary>The original question.</summary>
    public required string Question { get; init; }

    /// <summary>The reference answer (if provided).</summary>
    public string? ExpectedAnswer { get; init; }

    /// <summary>The answer generated by the RAG system.</summary>
    public required string GeneratedAnswer { get; init; }

    /// <summary>Contexts retrieved from the knowledge base for this query.</summary>
    public IReadOnlyList<string> RetrievedContexts { get; init; } = [];

    /// <summary>
    /// Faithfulness score [0..1] -- how grounded is the answer in the retrieved contexts.
    /// </summary>
    public double FaithfulnessScore { get; init; }

    /// <summary>
    /// Relevancy score [0..1] -- how relevant is the answer to the question.
    /// </summary>
    public double RelevancyScore { get; init; }

    /// <summary>Error message if this case failed to evaluate.</summary>
    public string? Error { get; init; }
}

/// <summary>
/// Aggregated result of an evaluation run over multiple QA test cases.
/// </summary>
public class EvalRunResult
{
    /// <summary>Individual case results.</summary>
    public IReadOnlyList<EvalCaseResult> Cases { get; init; } = [];

    /// <summary>Average faithfulness across all cases.</summary>
    public double AverageFaithfulness =>
        Cases.Count == 0 ? 0.0 : Cases.Average(c => c.FaithfulnessScore);

    /// <summary>Average relevancy across all cases.</summary>
    public double AverageRelevancy =>
        Cases.Count == 0 ? 0.0 : Cases.Average(c => c.RelevancyScore);

    /// <summary>Overall score -- average of faithfulness and relevancy.</summary>
    public double OverallScore => (AverageFaithfulness + AverageRelevancy) / 2.0;

    /// <summary>Number of cases that produced errors.</summary>
    public int ErrorCount => Cases.Count(c => c.Error is not null);

    /// <summary>Total elapsed time for the run.</summary>
    public TimeSpan Duration { get; init; }
}
